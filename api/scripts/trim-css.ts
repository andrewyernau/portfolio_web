import { readFileSync, writeFileSync } from "node:fs";
import postcss from "postcss";
import selectorParser, { type Selector } from "postcss-selector-parser";

const path = (file: string) => new URL(`../../${file}`, import.meta.url).pathname;

const SOURCE = "static/vendor/missing-1.3.0.min.css";
export const TRIMMED = "static/missing.trimmed.css";
// The views rather than rendered pages, so states such as form errors count as used.
const MARKUP = ["api/src/site/views.tsx", "api/src/site/routes.tsx", "static/site.js"];

const HEADER = "/* missing.css 1.3.0 without the rules this site cannot match. Generated by api/scripts/trim-css.ts. License in vendor/missing.LICENSE. */\n";

/** False only when the selector needs a name the markup never uses. Anything else stays. */
function canMatch(selector: Selector, used: Set<string>): boolean {
  return selector.nodes.every((node) => {
    if (node.type === "tag" || node.type === "class" || node.type === "id") return used.has(node.value);
    if (node.type === "attribute") return used.has(node.attribute);
    if (node.type === "pseudo" && (node.value === ":is" || node.value === ":where")) {
      return node.nodes.some((inner) => canMatch(inner, used));
    }
    return true;
  });
}

export function trim(): string {
  const markup = MARKUP.map((file) => readFileSync(path(file), "utf8")).join("\n");
  const used = new Set(markup.match(/[A-Za-z0-9_-]+/g));
  const root = postcss.parse(readFileSync(path(SOURCE), "utf8"));
  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && (rule.parent as postcss.AtRule).name.endsWith("keyframes")) return;
    const kept = rule.selectors.filter((selector) =>
      selectorParser().astSync(selector).nodes.some((parsed) => canMatch(parsed, used)),
    );
    // Nested rules take their specificity from the whole list, so it must stay intact.
    const nests = rule.some((node) => node.type === "rule");
    if (kept.length === 0) rule.remove();
    else if (!nests) rule.selectors = kept;
  });
  root.walkAtRules(/^(media|supports|layer)$/, (rule) => {
    if (rule.nodes?.length === 0) rule.remove();
  });
  return `${HEADER}${root.toString()}\n`;
}

if (import.meta.main) writeFileSync(path(TRIMMED), trim());
